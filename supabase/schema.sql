-- АВТОМАТИЧЕСКАЯ ОЧИСТКА
-- Сначала в Supabase Dashboard включите Integrations → Cron (pg_cron).
-- После этого выполните следующий блок.
--
-- Он запускает очистку каждый час. Записи удаляются через 24 часа после окончания,
-- а связанные participants удаляются автоматически благодаря ON DELETE CASCADE.
--
-- Если имя job уже существует, сначала удалите его в Dashboard → Integrations → Cron.

create or replace function public.cleanup_old_bookings()
returns void
language sql
security definer
set search_path = ''
as $$
  delete from public.bookings
  where end_at < now() - interval '24 hours';
$$;

revoke execute on function public.cleanup_old_bookings() from public;
revoke execute on function public.cleanup_old_bookings() from anon;
revoke execute on function public.cleanup_old_bookings() from authenticated;

-- Выполняется только планировщиком базы.
select cron.schedule(
  'cinema-cleanup-old-bookings',
  '0 * * * *',
  $$select public.cleanup_old_bookings()$$
)
where not exists (
  select 1 from cron.job where jobname = 'cinema-cleanup-old-bookings'
);
